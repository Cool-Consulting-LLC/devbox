package config

import (
	"fmt"
	"io"
	"reflect"
	"strings"
)

// Key is one leaf of devbox.yaml, as documented. Empty means default:"" was
// written out: the key is optional and off unless set.
type Key struct {
	Path, Type, Default, Tier, Describe string
	Empty                               bool
}

// Keys walks Config's struct tags. It is the single source for docs/config.md.
func Keys() []Key {
	var out []Key
	walk(reflect.TypeOf(Config{}), "", &out)
	return out
}

func walk(t reflect.Type, prefix string, out *[]Key) {
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		name := strings.Split(f.Tag.Get("yaml"), ",")[0]
		path := prefix + name
		ft := f.Type
		if ft.Kind() == reflect.Pointer {
			ft = ft.Elem()
		}
		if ft.Kind() == reflect.Struct {
			walk(ft, path+".", out)
			continue
		}
		typ := ft.Kind().String()
		switch ft.Kind() {
		case reflect.Int, reflect.Int64:
			typ = "integer"
		case reflect.Slice:
			typ = "list of " + ft.Elem().Kind().String()
		}
		def, ok := f.Tag.Lookup("default")
		*out = append(*out, Key{
			Path: path, Type: typ, Default: def, Empty: ok && def == "",
			Tier: f.Tag.Get("tier"), Describe: f.Tag.Get("describe"),
		})
	}
}

var tierText = map[string]string{
	TierIdentity:    "Selects a different box. Changing it addresses new resources; the old ones are left alone.",
	TierInPlace:     "`devbox apply` updates the GCP resource. The instance is not touched.",
	TierReprovision: "`devbox apply` updates instance metadata (and grows disks); `devbox reprovision` applies it on the box. No session lost.",
	TierRestart:     "`devbox apply` stops and starts the instance. Disks survive; tmux sessions do not.",
	TierReplace:     "`devbox apply` deletes and recreates the instance. `/srv/code` survives; home directories and sessions do not.",
	TierRefused:     "Not implemented. Setting it is an error.",
}

// WriteMarkdown renders docs/config.md.
func WriteMarkdown(w io.Writer) error {
	p := func(f string, a ...any) { fmt.Fprintf(w, f, a...) }
	p("<!-- Generated by `devbox config --describe`. Do not edit; run `make docs`. -->\n\n")
	p("# devbox.yaml reference\n\n")
	p("What does each value in `devbox.yaml` do? One row per key. Absent keys take the default. Unknown keys are an error.\n\n")
	p("| Key | Type | Default | Tier | What it does |\n|---|---|---|---|---|\n")
	for _, k := range Keys() {
		def := k.Default
		if def == "" {
			def = "*(required)*"
			if k.Empty || k.Tier == TierInPlace || k.Tier == TierRefused {
				def = "*(empty)*"
			}
		} else {
			def = "`" + def + "`"
		}
		p("| `%s` | %s | %s | %s | %s |\n", k.Path, k.Type, def, k.Tier, strings.ReplaceAll(k.Describe, "|", `\|`))
	}
	p("\n## Tiers\n\n| Tier | Meaning |\n|---|---|\n")
	for _, t := range []string{TierIdentity, TierInPlace, TierReprovision, TierRestart, TierReplace, TierRefused} {
		p("| %s | %s |\n", t, tierText[t])
	}
	p("\nA change to `cloud-init.yaml` in the binary itself is also **replace** tier. A change to `provision.sh` is **reprovision** tier.\n")
	return nil
}
