step ssh-agent
# Picks up the drop-in that reloads the key whenever the agent restarts.
systemctl daemon-reload
devbox-agent-load-key
pubkey=$(SSH_AUTH_SOCK=/run/devbox-agent/agent.sock ssh-add -L | head -n1)
# Admins reach the agent through the relay; pick up any change to its script.
systemctl restart devbox-ssh-agent-relay.service

step git
install -d -m 0755 /etc/devbox
printf '%s namespaces="git" %s\n' "$DEVBOX_GIT_EMAIL" "$pubkey" > /etc/devbox/allowed_signers
# Through git config, not a heredoc: git quotes the values, so nothing in
# devbox.yaml can add a line of its own to a file every git command reads.
gc=/etc/gitconfig.devbox-new
echo "# Written by provision.sh from devbox.yaml. ~/.gitconfig still overrides." > "$gc"
git config --file "$gc" user.name "$DEVBOX_GIT_NAME"
git config --file "$gc" user.email "$DEVBOX_GIT_EMAIL"
git config --file "$gc" user.signingkey "key::$pubkey"
git config --file "$gc" gpg.format ssh
git config --file "$gc" commit.gpgsign true
git config --file "$gc" tag.forceSignAnnotated true
git config --file "$gc" gpg.ssh.allowedSignersFile /etc/devbox/allowed_signers
git config --file "$gc" init.defaultBranch main
chmod 0644 "$gc" && mv "$gc" /etc/gitconfig
# Pin GitHub's host keys from its TLS-authenticated API, not from first contact.
gh_keys=$(curl -fsS https://api.github.com/meta | jq -r '.ssh_keys[] | "github.com " + .') || gh_keys=""
if [ -n "$gh_keys" ]; then
  { grep -v '^github.com ' /etc/ssh/ssh_known_hosts 2>/dev/null || true; echo "$gh_keys"; } > /etc/ssh/ssh_known_hosts.new
  mv /etc/ssh/ssh_known_hosts.new /etc/ssh/ssh_known_hosts
  chmod 0644 /etc/ssh/ssh_known_hosts
fi

step host-keys
# Same reasoning for the SSH host keys: keep them on the pet disk, or every
# replacement greets you with REMOTE HOST IDENTIFICATION HAS CHANGED, and a
# warning you are trained to click through is no warning at all.
hk=/srv/code/.devbox/ssh-host-keys
if [ -d "$hk" ]; then
  if ! cmp -s "$hk/ssh_host_ed25519_key" /etc/ssh/ssh_host_ed25519_key; then
    install -m 0600 "$hk"/ssh_host_*_key /etc/ssh/
    install -m 0644 "$hk"/ssh_host_*_key.pub /etc/ssh/
    systemctl restart ssh.service
    restart_tailscaled=1
  fi
else
  install -d -m 0700 "$hk"
  cp -p /etc/ssh/ssh_host_*_key /etc/ssh/ssh_host_*_key.pub "$hk/"
fi

step tailscale
# The node's identity lives on the pet disk, so a replaced instance comes back as
# the same tailnet device (same name, same IP) instead of devbox-1, devbox-2, ...
ts_state=/srv/code/.devbox/tailscale
if [ "$(readlink /var/lib/tailscale)" != "$ts_state" ]; then
  systemctl stop tailscaled
  if [ ! -d "$ts_state" ]; then
    # First run on this disk: adopt whatever identity this instance has.
    install -d -m 0700 "$ts_state"
    cp -a /var/lib/tailscale/. "$ts_state/" 2>/dev/null || true
  fi
  rm -rf /var/lib/tailscale
  ln -s "$ts_state" /var/lib/tailscale
fi
systemctl enable --now tailscaled
# Tailscale SSH presents the system host keys; make it pick up restored ones.
[ -n "${restart_tailscaled:-}" ] && systemctl restart tailscaled && sleep 2
state=$(tailscale status --json 2>/dev/null | jq -r .BackendState || echo NoState)
if [ "$state" != Running ]; then
  umask 077
  # The box may read the OAuth secret only for an hour after `devbox up` created
  # the code disk, and a fresh grant can take minutes to reach IAM.
  for i in $(seq 20); do
    devbox-secret "$DEVBOX_TS_SECRET" > /run/ts.key 2>/dev/null && break
    if [ "$i" = 20 ]; then
      rm -f /run/ts.key
      echo "cannot read secret $DEVBOX_TS_SECRET to join the tailnet. The box gets an hour" >&2
      echo "to read it after its code disk is created; from the laptop, run:" >&2
      echo "  devbox reprovision --iap --rejoin" >&2
      exit 1
    fi
    sleep 15
  done
  printf '?preauthorized=true&ephemeral=false' >> /run/ts.key
  umask 022
  tailscale up \
    --auth-key=file:/run/ts.key \
    --advertise-tags="$DEVBOX_TS_TAG" \
    --hostname="$DEVBOX_NAME" \
    --accept-dns=false \
    --ssh
  shred -u /run/ts.key
else
  tailscale set --hostname="$DEVBOX_NAME" --accept-dns=false --ssh
fi
