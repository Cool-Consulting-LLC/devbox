#!/bin/bash
# provision.sh: reprovision tier. Idempotent; safe to run any number of times.
# The canonical copy is in the devbox repo and embedded in the binary. The copy at
# /srv/code/.devbox/provision.sh is a cache. Push changes with `devbox reprovision`.
set -euo pipefail
exec > >(tee -a /var/log/devbox-provision.log) 2>&1
echo "=== provision $(date -Is)"
export DEBIAN_FRONTEND=noninteractive

MD=http://metadata.google.internal/computeMetadata/v1
md() { curl -fsS -H 'Metadata-Flavor: Google' "$MD/$1"; }
step() { echo "--- $*"; }

# @@WRITE_FILES@@

# Non-secret config, rendered from devbox.yaml into instance metadata by the binary.
install -d -m 0755 /run/devbox
md instance/attributes/devbox-config > /run/devbox/config.env.new
mv /run/devbox/config.env.new /run/devbox/config.env
# shellcheck source=/dev/null
. /run/devbox/config.env

# Box-side files. Generated by the binary from internal/assets/files/box.
step files
write_files

step disks
resize2fs /dev/disk/by-id/google-code >/dev/null 2>&1 || true
root_dev=$(findmnt -no SOURCE /)
growpart "/dev/$(lsblk -no PKNAME "$root_dev")" "${root_dev##*[!0-9]}" >/dev/null 2>&1 && resize2fs "$root_dev" >/dev/null || true

step layout
install -d -m 2775 -g google-sudoers /srv/code/.home /srv/code/.gcloud /srv/code/_out
install -d -m 2775 -g google-sudoers /srv/code/.gcloud/default

# OS Login grants sudo by writing /var/google-sudoers.d/<user> during an sshd
# login. Tailscale SSH never reaches that, so a replaced box would leave its
# owner without sudo. Grant the same thing here, for every user enrolled on this
# disk whom OS Login says holds adminLogin right now, and create their homes.
step admins
oslogin() { curl -fsS -H 'Metadata-Flavor: Google' "$MD/oslogin/$1"; }
sudoers=$(mktemp)
for m in /srv/code/.devbox/enrolled/*; do
  [ -e "$m" ] || continue
  uid=$(basename "$m")
  [[ $uid =~ ^[0-9]+$ ]] || { rm -f "$m"; continue; }   # name-keyed markers predate uids
  profile=$(oslogin "users?uid=$uid") || continue
  user=$(jq -r --arg uid "$uid" '.loginProfiles[0].posixAccounts[] | select(.uid == $uid) | .username' <<<"$profile" | head -n1)
  email=$(jq -r '.loginProfiles[0].name' <<<"$profile")
  [ -n "$user" ] || continue
  if oslogin "authorize?email=$email&policy=adminLogin" | jq -e .success >/dev/null 2>&1; then
    echo "$user ALL=(ALL:ALL) NOPASSWD: ALL" >> "$sudoers"
  fi
  home=$(getent passwd "$uid" | cut -d: -f6) || true
  if [ -n "$home" ] && [ ! -d "$home" ]; then mkhomedir_helper "$user" 0077; fi
done
if visudo -cqf "$sudoers"; then install -m 0440 "$sudoers" /etc/sudoers.d/devbox-admins; fi
rm -f "$sudoers"

step packages
apt_get() { for i in 1 2 3; do apt-get "$@" && return 0; sleep $((i * 10)); done; return 1; }
need_update=0

if [ ! -f /etc/apt/sources.list.d/claude-code.list ]; then
  install -d -m 0755 /etc/apt/keyrings
  curl -fsSL https://downloads.claude.ai/keys/claude-code.asc -o /etc/apt/keyrings/claude-code.asc.new
  if ! gpg --show-keys /etc/apt/keyrings/claude-code.asc.new | grep -q 31DDDE24DDFAB679F42D7BD2BAA929FF1A7ECACE; then
    echo "claude-code signing key fingerprint mismatch; refusing" >&2; exit 1
  fi
  mv /etc/apt/keyrings/claude-code.asc.new /etc/apt/keyrings/claude-code.asc
  echo "deb [signed-by=/etc/apt/keyrings/claude-code.asc] https://downloads.claude.ai/claude-code/apt/stable stable main" \
    > /etc/apt/sources.list.d/claude-code.list
  need_update=1
fi

if [ ! -f /etc/apt/sources.list.d/tailscale.list ]; then
  . /etc/os-release
  curl -fsSL "https://pkgs.tailscale.com/stable/ubuntu/${VERSION_CODENAME}.noarmor.gpg" \
    -o /usr/share/keyrings/tailscale-archive-keyring.gpg
  curl -fsSL "https://pkgs.tailscale.com/stable/ubuntu/${VERSION_CODENAME}.tailscale-keyring.list" \
    -o /etc/apt/sources.list.d/tailscale.list
  need_update=1
fi

# Refresh at most daily otherwise, so a reprovision stays quick.
if [ "$need_update" = 1 ] || [ -z "$(find /var/lib/apt/lists -maxdepth 0 -mmin -1440 2>/dev/null)" ]; then
  apt_get update -q
fi
# shellcheck disable=SC2086
apt_get install -y -q acl claude-code golang-go tailscale $DEVBOX_EXTRA_PACKAGES

step ssh-agent
export SSH_AUTH_SOCK=/run/devbox-agent/agent.sock
if ! ssh-add -l >/dev/null 2>&1; then
  devbox-secret "$DEVBOX_SSH_KEY_SECRET" | ssh-add -
fi
pubkey=$(ssh-add -L | head -n1)
# Admins reach the agent through the relay; pick up any change to its script.
systemctl restart devbox-ssh-agent-relay.service

step git
install -d -m 0755 /etc/devbox
printf '%s namespaces="git" %s\n' "$DEVBOX_GIT_EMAIL" "$pubkey" > /etc/devbox/allowed_signers
cat > /etc/gitconfig <<EOF
# Written by provision.sh from devbox.yaml. ~/.gitconfig still overrides.
[user]
	name = $DEVBOX_GIT_NAME
	email = $DEVBOX_GIT_EMAIL
	signingkey = key::$pubkey
[gpg]
	format = ssh
[commit]
	gpgsign = true
[tag]
	forceSignAnnotated = true
[gpg "ssh"]
	allowedSignersFile = /etc/devbox/allowed_signers
[init]
	defaultBranch = main
EOF
# Pin GitHub's host keys from its TLS-authenticated API, not from first contact.
gh_keys=$(curl -fsS https://api.github.com/meta | jq -r '.ssh_keys[] | "github.com " + .') || gh_keys=""
if [ -n "$gh_keys" ]; then
  { grep -v '^github.com ' /etc/ssh/ssh_known_hosts 2>/dev/null || true; echo "$gh_keys"; } > /etc/ssh/ssh_known_hosts.new
  mv /etc/ssh/ssh_known_hosts.new /etc/ssh/ssh_known_hosts
  chmod 0644 /etc/ssh/ssh_known_hosts
fi

step host-keys
# Same reasoning for the SSH host keys: keep them on the pet disk, or every
# replacement greets you with REMOTE HOST IDENTIFICATION HAS CHANGED, and a
# warning you are trained to click through is no warning at all.
hk=/srv/code/.devbox/ssh-host-keys
if [ -d "$hk" ]; then
  if ! cmp -s "$hk/ssh_host_ed25519_key" /etc/ssh/ssh_host_ed25519_key; then
    install -m 0600 "$hk"/ssh_host_*_key /etc/ssh/
    install -m 0644 "$hk"/ssh_host_*_key.pub /etc/ssh/
    systemctl restart ssh.service
    restart_tailscaled=1
  fi
else
  install -d -m 0700 "$hk"
  cp -p /etc/ssh/ssh_host_*_key /etc/ssh/ssh_host_*_key.pub "$hk/"
fi

step tailscale
# The node's identity lives on the pet disk, so a replaced instance comes back as
# the same tailnet device (same name, same IP) instead of devbox-1, devbox-2, ...
ts_state=/srv/code/.devbox/tailscale
if [ "$(readlink /var/lib/tailscale)" != "$ts_state" ]; then
  systemctl stop tailscaled
  if [ ! -d "$ts_state" ]; then
    # First run on this disk: adopt whatever identity this instance has.
    install -d -m 0700 "$ts_state"
    cp -a /var/lib/tailscale/. "$ts_state/" 2>/dev/null || true
  fi
  rm -rf /var/lib/tailscale
  ln -s "$ts_state" /var/lib/tailscale
fi
systemctl enable --now tailscaled
# Tailscale SSH presents the system host keys; make it pick up restored ones.
[ -n "${restart_tailscaled:-}" ] && systemctl restart tailscaled && sleep 2
state=$(tailscale status --json 2>/dev/null | jq -r .BackendState || echo NoState)
if [ "$state" != Running ]; then
  umask 077
  devbox-secret "$DEVBOX_TS_SECRET" > /run/ts.key
  printf '?preauthorized=true&ephemeral=false' >> /run/ts.key
  umask 022
  tailscale up \
    --auth-key=file:/run/ts.key \
    --advertise-tags="$DEVBOX_TS_TAG" \
    --hostname="$DEVBOX_NAME" \
    --accept-dns=false \
    --ssh
  shred -u /run/ts.key
else
  tailscale set --hostname="$DEVBOX_NAME" --accept-dns=false --ssh
fi

step motd
# Quiet logins: no Ubuntu banner, legal notice, news or update nags. The
# .bashrc prints what is worth knowing (uptime, tmux sessions).
chmod -x /etc/update-motd.d/* 2>/dev/null || true
: > /etc/legal
if [ -f /etc/default/motd-news ]; then sed -i 's/^ENABLED=.*/ENABLED=0/' /etc/default/motd-news; fi
systemctl disable --now motd-news.timer 2>/dev/null || true
rm -f /run/motd.dynamic

step idle-suspend
if [ "$DEVBOX_IDLE_ENABLED" = true ]; then
  systemctl enable --now devbox-idle.timer
else
  systemctl disable --now devbox-idle.timer
fi

echo "=== provision done $(date -Is)"
